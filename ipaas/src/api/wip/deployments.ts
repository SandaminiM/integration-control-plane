export async function triggerBuild(input: DeployComponentInput): Promise<{ message: string; success: boolean }> {
  return gql<{ deployComponent: { message: string; success: boolean } }>(DEPLOY_COMPONENT, {
    componentId: input.componentId,
    versionId: input.versionId,
    envId: input.envId,
    sha: input.sha,
    branch: input.branch,
    shaDate: input.shaDate ?? '',
    gitRefType: input.gitRefType,
    cron: input.cron ?? null,
    cronTimezone: input.cronTimezone ?? '',
    commitTag: input.commitTag ?? null,
  }).then((d) => d.deployComponent);
}

