export async function fetchComponentDeployment(orgHandler: string, orgUuid: string, componentId: string, versionId: string, environmentId: string): Promise<ComponentDeployment | null> {
  return gql<{ componentDeployment: ComponentDeployment }>(COMPONENT_DEPLOYMENT_QUERY, { orgHandler, orgUuid, componentId, versionId, environmentId })
    .then((d) => d.componentDeployment)
    .catch((): null => null);
}

export async function fetchEnvEndpoints(componentId: string, versionId: string, releaseId: string): Promise<EnvEndpoint[]> {
  return gql<{ componentEndpoints: EnvEndpoint[] }>(ENV_ENDPOINTS_QUERY, { componentId, versionId, releaseId })
    .then((d) => d.componentEndpoints ?? [])
    .catch(() => []);
}

// ── Raw wire shapes — private to this file. The GraphQL responses come back
// with snake_case fields; mappers below convert them to the camelCase domain
// types declared in `src/types/deployment.ts` before the data leaves this file.

interface RawBuildRun {
  id: number;
  sha: string;
  started_at: string;
  completed_at: string;
  status: string;
  conclusion: string;
  conclusionV2: string;
  isAutoDeploy: boolean;
  isTriggeredAtCreation: boolean;
  name: string;
  failureReason: number;
  sourceCommitId: string;
  buildRef?: string;
}

interface RawReleaseMgtDeployment {
  id: string;
  release_mgt_id: string;
  environment_id: string;
  deployment_name: string;
  attempt: number;
  config_revision: number;
  status: string;
  comment: string;
  deployed_at: string;
  deployed_by: string;
  release_name: string;
  commit_hash: string;
  component_configs: {
    config_mapping_revision: number;
    schema_based_config_revision: number;
    api_settings: string;
  };
  created_at: string;
}

function toBuildRun(raw: RawBuildRun): BuildRun {
  return {
    id: raw.id,
    sha: raw.sha,
    startedAt: raw.started_at,
    completedAt: raw.completed_at,
    status: raw.status,
    conclusion: raw.conclusion,
    conclusionV2: raw.conclusionV2,
    isAutoDeploy: raw.isAutoDeploy,
    isTriggeredAtCreation: raw.isTriggeredAtCreation,
    name: raw.name,
    failureReason: raw.failureReason,
    sourceCommitId: raw.sourceCommitId,
    buildRef: raw.buildRef,
  };
}

function toReleaseMgtDeployment(raw: RawReleaseMgtDeployment): ReleaseMgtDeployment {
  return {
    id: raw.id,
    releaseMgtId: raw.release_mgt_id,
    environmentId: raw.environment_id,
    deploymentName: raw.deployment_name,
    attempt: raw.attempt,
    configRevision: raw.config_revision,
    status: raw.status,
    comment: raw.comment,
    deployedAt: raw.deployed_at,
    deployedBy: raw.deployed_by,
    releaseName: raw.release_name,
    commitHash: raw.commit_hash,
    componentConfigs: {
      configMappingRevision: raw.component_configs.config_mapping_revision,
      schemaBasedConfigRevision: raw.component_configs.schema_based_config_revision,
      apiSettings: raw.component_configs.api_settings,
    },
    createdAt: raw.created_at,
  };
}

export async function fetchDeploymentStatus(componentId: string, versionId: string): Promise<BuildRun[]> {
  return gql<{ deploymentStatusByVersion: RawBuildRun[] }>(DEPLOYMENT_STATUS_QUERY, { versionId, componentId }).then((d) => (d.deploymentStatusByVersion ?? []).map(toBuildRun));
}

export async function fetchReleaseMgtDeployments(orgUuid: string, projectId: string, componentId: string, versionId: string, environmentId: string): Promise<ReleaseMgtDeployment[]> {
  const query = `query {
    componentReleaseMgtDeployments(input: {
      organization_id: "${esc(orgUuid)}"
      project_id: "${esc(projectId)}"
      component_id: "${esc(componentId)}"
      deployment_track_id: "${esc(versionId)}"
      environment_id: "${esc(environmentId)}"
      offset: 0
      limit: 10
    }) {
      deployments {
        id, release_mgt_id, environment_id, deployment_name, attempt,
        config_revision, status, comment, deployed_at, deployed_by,
        release_name, commit_hash,
        component_configs { config_mapping_revision, schema_based_config_revision, api_settings }
        created_at
      }
    }
  }`;
  return gql<{ componentReleaseMgtDeployments: { deployments: RawReleaseMgtDeployment[] } }>(query)
    .then((d) => (d.componentReleaseMgtDeployments?.deployments ?? []).map(toReleaseMgtDeployment))
    .catch(() => [] as ReleaseMgtDeployment[]);
}

